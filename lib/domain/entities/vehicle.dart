class Vehicle {
  const Vehicle({
    required this.id,
    required this.plate,
    required this.driver,
    required this.route,
    required this.speed,
    required this.status,
    required this.students,
    required this.x,
    required this.y,
  });

  final String id;
  final String plate;
  final String driver;
  final String route;
  final num speed;
  final String status;
  final int students;
  final num x;
  final num y;
}
